# ---------- Unified Emergency Orchestrator Result (Step 7) ----------
class AssessmentResult(BaseModel):
    """Unified emergency assessment result assembled by the Emergency Orchestrator (Step 7).

    Coordinates triage category, deterministic weather risk, structured action plan,
    weakest-link confidence, optional hospital list, and optional explicit SOS response.
    Also provides legacy fields for backward compatibility with existing clients.
    """
    model_config = ConfigDict(extra="ignore")

    # Structured Orchestration Data
    triage: TriageResult
    weather: Optional[dict] = None
    action_plan: ActionPlan
    confidence: ConfidenceResult
    hospitals: list[HospitalOut] = Field(default_factory=list)
    sos: Optional[SosResponse] = None
    service_status: dict[str, str] = Field(default_factory=dict)

    # Backward-Compatible Legacy Fields
    emergency_level: str = "Moderate"
    whats_happening: str = ""
    immediate_first_aid: list[str] = Field(default_factory=list)
    what_not_to_do: list[str] = Field(default_factory=list)
    call_these_services: list[str] = Field(default_factory=list)
    things_to_carry: list[str] = Field(default_factory=list)
    nearby_help: list[dict] = Field(default_factory=list)
    raw_text: str = ""


