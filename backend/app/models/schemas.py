# ---------- Triage classification ----------
EmergencyCategory = Literal[
    "flooding",
    "electrocution",
    "injury",
    "snakebite",
    "cyclone",
    "structural_damage",
    "accident",
    "unclassified",
]

TriageTier = Literal[1, 2, 3]


class TriageResult(BaseModel):
    """Output of the three-tier triage classification cascade.

    Determines *what type* of incident this is.
    Never determines severity — that is the exclusive domain of the
    deterministic weather/risk score (Principle 2).
    """
    category: EmergencyCategory
    confidence: float = Field(..., ge=0.0, le=1.0, description="0.0–1.0")
    tier: TriageTier = Field(..., description="1=keyword, 2=embedding, 3=LLM fallback")
    matched_rule_or_example: Optional[str] = Field(
        None,
        description="Human-readable label of the matched keyword/phrase or example sentence.",
    )
    explanation: str = Field(..., description="Why this category was chosen (deterministic for Tiers 1–2).")


# ---------- Structured Action Planning (Step 5) ----------
class ActionPlan(BaseModel):
    """Strictly structured emergency action plan generated by LLM or deterministic fallback.

    The LLM acts as an action-planning assistant only.
    It MUST NOT contain: severity, emergency_level, triage category,
    weather risk score, confidence score, routing decisions, hospital
    recommendations, or arbitrary URLs.
    """
    model_config = ConfigDict(extra="ignore")

    immediate_actions: list[Annotated[str, Field(max_length=500)]] = Field(
        ..., min_length=1, max_length=15, description="Prioritized immediate safety steps"
    )
    safety_warnings: list[Annotated[str, Field(max_length=500)]] = Field(
        default_factory=list, max_length=15, description="Things NOT to do / critical warnings"
    )
    when_to_seek_help: list[Annotated[str, Field(max_length=500)]] = Field(
        default_factory=list, max_length=15, description="Specific triggers requiring immediate escalation"
    )
    questions_to_ask_user: list[Annotated[str, Field(max_length=500)]] = Field(
        default_factory=list, max_length=10, description="Clarifying questions if genuinely necessary"
    )
    emergency_contacts: list[Annotated[str, Field(max_length=200)]] = Field(
        default_factory=list, max_length=10, description="Trusted emergency helpline numbers"
    )
    explanation: Annotated[str, Field(max_length=1000)] = Field(
        ..., description="Brief, concise rationale for the recommended actions"
    )

    @field_validator("immediate_actions", "safety_warnings", "when_to_seek_help", "questions_to_ask_user", mode="after")
    @classmethod
    def reject_urls_in_lists(cls, v: list[str]) -> list[str]:
        url_pattern = re.compile(r"(https?://\S+|www\.\S+)", re.IGNORECASE)
        for item in v:
            if url_pattern.search(item):
                raise ValueError(f"Action plan item cannot contain arbitrary URLs: {item}")
        return v

    @field_validator("explanation", mode="after")
    @classmethod
    def reject_urls_in_explanation(cls, v: str) -> str:
        url_pattern = re.compile(r"(https?://\S+|www\.\S+)", re.IGNORECASE)
        if url_pattern.search(v):
            raise ValueError(f"Action plan explanation cannot contain arbitrary URLs: {v}")
        return v


