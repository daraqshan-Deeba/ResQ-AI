# ---------- Confidence Aggregation (Step 6) ----------
ConfidenceLevel = Literal["high", "medium", "low"]
ActionPlanSource = Literal["deterministic", "groq"]


class ConfidenceResult(BaseModel):
    """Centralized aggregated confidence assessment following weakest-link principle.

    All confidence values are strictly between 0.0 and 1.0.
    The LLM has zero authority over confidence or severity.
    """
    model_config = ConfigDict(extra="forbid")

    overall_confidence: float = Field(..., ge=0.0, le=1.0, description="Weakest-link overall confidence score")
    confidence_level: ConfidenceLevel = Field(..., description="Categorical confidence: high >= 0.80, medium >= 0.50, low < 0.50")
    triage_confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence of triage classification")
    weather_confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence of weather signal availability")
    action_plan_confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence in action-plan provenance (deterministic=1.0, groq=0.35)")
    limiting_factor: str = Field(..., description="Subsystem responsible for capping overall confidence")


